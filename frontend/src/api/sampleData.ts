const SAMPLE_DAILY_RESULTS = SAMPLE_DATES.slice(-4).map((dataDate, dayIndex) => {
  const dayPrices = PRICE_SERIES.map(({ prices }) => prices[prices.length - 4 + dayIndex]);
  const dayConsensus = dayPrices.reduce((sum, price) => sum + price, 0) / dayPrices.length;
  return {
    data_date: dataDate,
    equal_weight_consensus: dayConsensus,
    liquidity_weighted_consensus: dayConsensus,
    liquidity_weighting_method: 'not_applicable_to_sample',
    liquidity_weighting_note: 'Static sample diagnostics only.',
    contracts_included: dayPrices.length,
    contracts: [],
    candidates: [],
  };
});

const SAMPLE_IMPORTS = [{
  import_id: 'frontend-sample-only',
  file_name: 'Static sample fixture (not an upload)',
  source_name: 'Frontend sample data',
  data_mode: 'synthetic',
  status: 'sample-only',
  summary: { valid_rows: SAMPLE_OBSERVATIONS.length, total_rows: SAMPLE_OBSERVATIONS.length },
  error: null,
  last_updated: `${SAMPLE_DATES[SAMPLE_DATES.length - 1]}T12:00:00Z`,
}];

export function createSampleFetch(): typeof fetch {
  return async (input) => {
    const url = new URL(String(input), 'http://sample.local');
    let body: unknown;
    if (url.pathname === '/health') {
      body = { status: 'sample-preview', app: 'AURUM EDGE frontend fixture', database: 'not applicable' };
    } else if (url.pathname === '/api/v1/market/summary') {
      body = { data_sets: [SAMPLE_DATA_SET] };
    } else if (url.pathname === '/api/v1/market/observations') {
      const mode = url.searchParams.get('data_mode');
      const symbol = url.searchParams.get('symbol');
      body = SAMPLE_OBSERVATIONS.filter((row) => (!mode || row.data_mode === mode) && (!symbol || row.symbol === symbol));
    } else if (url.pathname === '/api/v1/contracts') {
      body = SAMPLE_CONTRACTS;
    } else if (url.pathname === '/api/v1/alerts') {
      body = SAMPLE_ALERTS;
    } else if (url.pathname === '/api/v1/analysis/backtest') {
      const startDate = url.searchParams.get('start_date');
      const endDate = url.searchParams.get('end_date');
      const dailyResults = SAMPLE_DAILY_RESULTS.filter((day) =>
        (!startDate || day.data_date >= startDate) && (!endDate || day.data_date <= endDate),
      );
      body = {
        method: 'Static illustrative daily observations; no strategy performance evaluated.',
        liquidity_weighting_method: 'not_applicable_to_sample',
        liquidity_weighting_note: 'Sample fixture only.',
        start_date: dailyResults[0]?.data_date ?? null,
        end_date: dailyResults[dailyResults.length - 1]?.data_date ?? null,
        days_evaluated: dailyResults.length,
        candidate_count: 0,
        trading_performance_claimed: false,
        daily_results: dailyResults,
      };
    } else if (url.pathname === '/api/v1/data/imports') {
      body = SAMPLE_IMPORTS;
    } else {
      return new Response(JSON.stringify({ detail: 'Sample preview does not perform backend operations.' }), {
        status: 503,
        headers: { 'Content-Type': 'application/json' },
      });
    }
    return new Response(JSON.stringify(body), {
      status: 200,
      headers: { 'Content-Type': 'application/json' },
    });
  };
}
